"""Retire reproducible completed math caches after a durable report handoff.

Keep bounded input/completion metadata and file digests, not raw factor bytes.
User reports, session indexes, the blockchain and wallets are outside this root.
The caller owns the provider journal lock; deletion follows one durable intent.
"""
from pathlib import Path
import hashlib
import json
import os
import re

from horizon_preparation_process import canonical, regular
from horizon_preparation_queue import (
    _directory, MAX_ATTEMPT_RECORDS, MAX_RETAINED_BYTES,
    MAX_RETAINED_FILES, MAX_RETAINED_DIRECTORIES,
)
from pgn_session import atomic_bytes

MAX_RECORD = 512 * 1024
MAX_SOURCE_BYTES = MAX_RETAINED_BYTES


def _identity(value):
    if type(value) is not str or not re.fullmatch('[0-9a-f]{64}', value):
        raise ValueError('Exact completed preparation identity required')
    return value


def _sha(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for part in iter(lambda: stream.read(65536), b''):
            h.update(part)
    return h.hexdigest()


def _attempt_name(name):
    match=re.fullmatch(r'attempt-([1-9][0-9]*)',name)
    return match is not None and 1<=int(match[1])<=MAX_ATTEMPT_RECORDS


def _owned_name(group, relative, directory=False):
    parts = Path(relative).parts
    if directory:
        return (not parts or group == 'job' and len(parts) in (1, 2)
                and _attempt_name(parts[0])
                and (len(parts) == 1 or parts[1] == 'output'))
    name = parts[-1]
    # Only temporaries generated by atomic_bytes, never arbitrary user files.
    name = re.sub(r'\.pending-[0-9]+-[0-9]+-[0-9a-f]{32}$', '', name)
    if group == 'plan':
        return len(parts) == 1 and name in ('input.json', 'job.json')
    if len(parts) == 1:
        return name == 'scopes.json'
    if not _attempt_name(parts[0]):
        return False
    if len(parts) == 2:
        return name in ('.controller.lock', 'request.json', 'producer-owner.json',
                        'producer-identity.json', 'producer-output.log', 'producer-receipt.json',
                        'producer-failure.json', 'ready.json', 'abandoned.json', 'cancelled.json')
    return (len(parts) == 3 and parts[1] == 'output'
            and (name in ('COMPLETE.json', 'COMPLETE.json.tmp')
                 or re.fullmatch(r'scope-(?:[0-9]|[1-5][0-9]|6[0-3])\.factors', name) is not None))


class PreparationRetention:
    def __init__(self, root):
        self.root = _directory(root).resolve()
        self.records = _directory(self.root / 'retired')
        self.intent = self.root / 'retire-intent.json'

    def record(self, identity):
        _directory(self.records)
        file = self.records / (_identity(identity) + '.json')
        value = json.loads(regular(file, MAX_RECORD))
        if (type(value) is not dict or value.get('schema') != 'PGN_RETIRED_PREPARATION_CACHE_V1'
                or value.get('plan') != identity or value.get('durable_handoff') is not True
                or value.get('raw_factor_bytes_retained') is not False):
            raise ValueError('Retired preparation metadata changed')
        _identity(value.get('job'))
        return value

    def _targets(self, plan, job):
        targets = dict(plan=self.root / 'plans' / _identity(plan),
                       job=self.root / 'preparation' / 'jobs' / _identity(job))
        for path in targets.values():
            # Check every existing ancestor before any traversal or deletion.
            if not path.resolve().is_relative_to(self.root) or path.resolve() == self.root:
                raise ValueError('Preparation cache target escaped its owned root')
            for ancestor in [path, *path.parents]:
                if ancestor == self.root.parent:
                    break
                if ancestor.exists() and (ancestor.is_symlink() or getattr(ancestor.lstat(), 'st_file_attributes', 0) & 0x400):
                    raise ValueError('Preparation cache target contains a reparse point')
        return targets

    def _manifest(self, targets):
        files = {}
        directories = []
        total = 0
        def unreadable(error):
            raise error
        for group, root in targets.items():
            if not root.exists():
                continue
            if not root.is_dir():
                raise ValueError('Preparation cache target is not a directory')
            for parent, dirs, names in os.walk(root, followlinks=False, onerror=unreadable):
                parent = Path(parent)
                if not _owned_name(group, parent.relative_to(root), directory=True):
                    raise ValueError('Unexpected directory in generated preparation cache; nothing deleted')
                directories.append(parent)
                if len(directories) > MAX_RETAINED_DIRECTORIES:
                    raise BufferError('Preparation retirement directory budget exceeded')
                for name in [*dirs, *names]:
                    path = parent / name
                    info = path.lstat()
                    if path.is_symlink() or getattr(info, 'st_file_attributes', 0) & 0x400:
                        raise ValueError('Preparation retirement cannot follow a reparse point')
                for name in names:
                    path = parent / name
                    if not _owned_name(group, path.relative_to(root)):
                        raise ValueError('Unexpected file in generated preparation cache; nothing deleted')
                    if not path.is_file():
                        raise ValueError('Unexpected cache entry type')
                    size = path.stat().st_size
                    total += size
                    if total > MAX_SOURCE_BYTES or len(files) >= MAX_RETAINED_FILES:
                        raise BufferError('Preparation retirement source budget exceeded')
                    files[group + '/' + path.relative_to(root).as_posix()] = dict(bytes=size, sha256=_sha(path))
        return files, directories

    def retire_locked(self, plan, job, *, delete_job, metadata):
        """Provider lock and durable consumer acknowledgement are prerequisites."""
        if type(delete_job) is not bool:
            raise ValueError('Explicit completed-cache ownership decision required')
        self.recover_locked()
        targets = self._targets(plan, job)
        if not targets['plan'].exists():
            record = self.record(plan)
            if record['job'] != job:
                raise ValueError('Retired plan changed its producer job')
            return record
        files, directories = self._manifest(targets)
        directory_names = sorted(group + '/' + path.relative_to(root).as_posix()
                                 for group, root in targets.items() for path in directories
                                 if path.is_relative_to(root))
        record = dict(schema='PGN_RETIRED_PREPARATION_CACHE_V1', plan=plan, job=job,
                      durable_handoff=True, raw_factor_bytes_retained=False,
                      source_recomputable=True, files=files, directories=directory_names, metadata=metadata)
        encoded = canonical(record) + b'\n'
        if len(encoded) > MAX_RECORD:
            raise BufferError('Compact preparation provenance exceeds its budget')
        file = self.records / (plan + '.json')
        atomic_bytes(file, encoded)
        intent = dict(schema='PGN_PREPARATION_RETIRE_INTENT_V1', plan=plan, job=job,
                      delete_job=delete_job, record_sha256=hashlib.sha256(encoded).hexdigest())
        atomic_bytes(self.intent, canonical(intent) + b'\n')
        self.recover_locked()
        return record

    def recover_locked(self):
        if not self.intent.exists():
            return
        intent = json.loads(regular(self.intent, 32768))
        if (type(intent) is not dict or set(intent) != {'schema', 'plan', 'job', 'delete_job', 'record_sha256'}
                or intent['schema'] != 'PGN_PREPARATION_RETIRE_INTENT_V1'
                or type(intent['delete_job']) is not bool):
            raise ValueError('Invalid preparation retirement intent')
        plan, job = _identity(intent['plan']), _identity(intent['job'])
        raw = regular(self.records / (plan + '.json'), MAX_RECORD)
        if hashlib.sha256(raw).hexdigest() != intent['record_sha256']:
            raise ValueError('Preparation retirement lost its compact provenance')
        record = self.record(plan)
        if record['job'] != job or type(record.get('files')) is not dict:
            raise ValueError('Preparation retirement identity changed')
        targets = self._targets(plan, job)
        if not intent['delete_job']:
            targets.pop('job')
        current, directories = self._manifest(targets)
        expected = {key: value for key, value in record['files'].items()
                    if key.startswith('plan/') or intent['delete_job'] and key.startswith('job/')}
        for name, value in current.items():
            if expected.get(name) != value:
                raise ValueError('Preparation cache changed or contains unrecorded data; nothing deleted')
        current_directories = [group + '/' + path.relative_to(root).as_posix()
                               for group, root in targets.items() for path in directories
                               if path.is_relative_to(root)]
        if any(value not in record.get('directories', []) for value in current_directories):
            raise ValueError('Unrecorded preparation directory; nothing deleted')
        # Missing recorded files are a possible interrupted deletion. Every
        # still-existing byte has just been verified; no unlisted file is pruned.
        for name in current:
            group, relative = name.split('/', 1)
            path = targets[group] / relative
            if not path.resolve().is_relative_to(targets[group].resolve()):
                raise ValueError('Preparation retirement path escaped its exact target')
        for name in current:
            group, relative = name.split('/', 1)
            (targets[group] / relative).unlink()
        for path in sorted(directories, key=lambda p: len(p.parts), reverse=True):
            path.rmdir()
        self.intent.unlink()

    def rotate_locked(self, keep=256):
        """Only old terminal cache provenance rotates; user history is elsewhere."""
        if type(keep) is not int or not 1 <= keep <= 256:
            raise ValueError('Bounded retired cache retention required')
        self.recover_locked()
        _directory(self.records)
        entries = []
        inspected = 0
        for file in self.records.iterdir():
            inspected += 1
            if inspected > 512:
                raise BufferError('Retired preparation record directory exceeds its budget')
            pending = re.fullmatch(r'([0-9a-f]{64})\.json\.pending-[0-9]+-[0-9]+-[0-9a-f]{32}', file.name)
            if pending is not None:
                partial = regular(file, MAX_RECORD)
                committed = self.records / (pending[1] + '.json')
                if committed.exists() and regular(committed, MAX_RECORD).startswith(partial):
                    file.unlink()
                # Unpublished nonmatching cache metadata is retained for
                # diagnosis within this bounded envelope, never made authority.
                continue
            if not re.fullmatch(r'[0-9a-f]{64}\.json', file.name):
                raise ValueError('Unexpected retired preparation file; no automatic pruning')
            self.record(file.stem)
            entries.append(file)
        entries.sort(key=lambda p: (p.stat().st_mtime_ns, p.name))
        for file in entries[:-keep]:
            file.unlink()
