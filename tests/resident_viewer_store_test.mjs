import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {HistoryStore} from '../tools/history-store.mjs';
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'pgn-resident-viewer-'));
const file=path.join(directory,'history.sqlite'),run='a'.repeat(32);
const writer=new HistoryStore(file,{indexed:true});
writer.append(['[phase0-gpu] GAP merit=3.5 gap=224 lower=1001 upper=1225 verified=1'],run,'native/'+run+'.stdout',99);
const reader=new HistoryStore(file,{indexed:true,readOnly:true});
assert.equal(reader.count(),1);assert.equal(reader.cursorOffset('native/'+run+'.stdout'),99);
assert.equal(reader.latest(1)[0].gap,'224');
assert.deepEqual(reader.plot.publication(run),writer.plot.publication(run));
assert.throws(()=>reader.append([],run,'native/'+run+'.stdout',999),/cannot write/);
writer.append(['[phase0-gpu] GAP merit=4 gap=226 lower=2001 upper=2227 verified=1'],run,'native/'+run+'.stdout',199);
assert.equal(reader.count(),2);assert.equal(reader.cursorOffset('native/'+run+'.stdout'),199);
assert.equal(reader.plot.publication(run).current.length.points,2);
reader.close();writer.close();
console.log(JSON.stringify({status:'PASS',read_only_viewer:true,live_committed_updates:true,scientific_writes:0,temporary_fixture:directory}));
